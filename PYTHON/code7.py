# range()
print("Range:")
for i in range(1, 6):
    print(i)

# while loop
print("\nWhile Loop:")
count = 1
while count <= 5:
    print(count)
    count += 1

# for loop
print("\nFor Loop:")
for i in range(1, 6):
    print(i)

# break
print("\nBreak:")
for i in range(1, 11):
    if i == 7:
        break
    print(i)

# continue
print("\nContinue:")
for i in range(1, 11):
    if i == 6:
        continue
    print(i)